#!/usr/bin/env node
/**
 * scripts/dev-pwa-identity.js — what makes the DEV app installable as its own,
 * visibly different thing on a home screen. Dev only; nothing here ships.
 *
 * ── ⛔ THE PROBLEM ──────────────────────────────────────────────────────────
 * There are TWO installed apps: the published one (from `main`, its own origin)
 * and this dev one (the tailnet origin). Separate origins mean separate installs,
 * separate workers and separate caches — all correct and all wanted. But the
 * manifest is the SAME FILE, so both installed as `RobCo U.O.S.` with the same
 * icon. ⭐ Two identical icons on one home screen is not a cosmetic problem: the
 * owner opens one believing it is the other, and every conclusion he draws after
 * that is about the wrong build. "Why is my change not here" and "why is this
 * showing unreleased work" are the same mistake seen from two directions.
 *
 * ── ⭐ THE DEV MANIFEST IS DERIVED, NEVER FORKED ────────────────────────────
 * This does NOT keep a second copy of manifest.json. It reads the real one and
 * overrides exactly three fields — `name`, `short_name`, `icons` — so everything
 * else (start_url, scope, display, shortcuts, colours) stays whatever the real
 * manifest says, and a future edit to it is inherited rather than missed. A
 * forked manifest is a manifest that silently stops matching.
 *
 * ⚠ `start_url` and `scope` are deliberately NOT touched. They are `./` in the
 * real manifest, which resolves RELATIVE TO THE MANIFEST'S OWN URL — so at
 * `/terminal/manifest.json` they already resolve to `/terminal/`. Measured with
 * Chrome's own manifest parser: zero errors, scope and start_url both
 * `https://<tailnet-host>/terminal/`. Rewriting them would break that, not fix it.
 *
 * ⛔ IT CANNOT REACH A PUBLISHED SURFACE. Same structure as the environment
 * marker (scripts/dev-env-marker.js): an `apply:'serve'` route, so it exists only
 * inside a running dev server. The tracked manifest.json is untouched, and
 * production serves that file straight from the repository. Guarded by Suite
 * 249.13.
 *
 * ── ⭐ WHY AN SVG ICON RATHER THAN A SECOND PNG IN THE REPO ────────────────
 * A committed dev icon would be a served, precached asset in a PUBLIC repo,
 * carried in every clone and every production build, for a surface only this
 * machine can reach. An SVG generated by the dev server costs the repository
 * nothing and cannot ship. ⚠ Chrome's installability check is satisfied by an
 * `image/svg+xml` icon declared `sizes: "any"` — asserted against Chrome's own
 * verdict rather than assumed, because an icon it rejects would take
 * installability down with it, which is worse than two identical icons.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const DEV_NAME = 'RobCo U.O.S. [DEV]';
const DEV_SHORT_NAME = 'RobCo DEV';
const DEV_ICON_FILE = 'dev-icon.svg';

/**
 * The dev icon: AMBER, where the real one is green. Colour does the work — it is
 * what reads at home-screen size, long before any text does. The word DEV is
 * there for the case where two amber things ever exist.
 */
function devIconSvg() {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
  <rect width="512" height="512" fill="#120d02"/>
  <rect x="26" y="26" width="460" height="460" rx="52" fill="none" stroke="#f5a623" stroke-width="26"/>
  <text x="256" y="238" text-anchor="middle" font-family="Consolas,Menlo,monospace"
        font-size="184" font-weight="bold" fill="#f5a623">R</text>
  <rect x="76" y="292" width="360" height="104" rx="14" fill="#f5a623"/>
  <text x="256" y="368" text-anchor="middle" font-family="Consolas,Menlo,monospace"
        font-size="86" font-weight="bold" fill="#120d02" letter-spacing="10">DEV</text>
</svg>`;
}

/**
 * Derive the dev manifest from the real one. Reads the real manifest itself so
 * there is exactly ONE reader of that file on this path; `realManifestText` is
 * an injection point for the guard, which must be able to drive this with a
 * known input rather than whatever the repository happens to contain today.
 */
function devManifest(realManifestText) {
  const text =
    realManifestText === undefined
      ? fs.readFileSync(path.join(__dirname, '..', 'manifest.json'), 'utf8')
      : realManifestText;
  const m = JSON.parse(text);
  m.name = DEV_NAME;
  m.short_name = DEV_SHORT_NAME;
  m.icons = [
    {
      src: DEV_ICON_FILE,
      sizes: 'any',
      type: 'image/svg+xml',
      purpose: 'any maskable',
    },
  ];
  return m;
}

module.exports = { DEV_NAME, DEV_SHORT_NAME, DEV_ICON_FILE, devIconSvg, devManifest };
